"""Build BROWSER.GO1: a simple HTML browser with HTTPS (BearSSL) for the GO1 loader.

python -m tools.build_browser [--card IMG]
Inputs (analysis/toolchains, not in git):
  bearssl-src/bearssl-0.6/ - BearSSL 0.6 from https://www.bearssl.org/bearssl-0.6.tar.gz
  cacert.pem               - Mozilla root certificates as published by curl (https://curl.se/ca/cacert.pem)
Generates analysis/browser/browser_data.c (trust anchors and the JVM bitmap fonts), compiles
apps/browser/browser.c with BearSSL and installs the program on the CUT card.
"""
import argparse
import base64
import re
from pathlib import Path

from emulator.board import ROOT
from .build_jvm import LIBRARY, build_library
from .build_native_app import compile_native

TOOLCHAINS = ROOT/'analysis/toolchains'
BEARSSL = TOOLCHAINS/'bearssl-src/bearssl-0.6'
CERTIFICATES = TOOLCHAINS/'cacert.pem'
OUTPUT = ROOT/'analysis/browser'
SOURCE = ROOT/'apps/browser/browser.c'
# BearSSL runs in ARM state: ARMv4T Thumb has no 32x32->64 multiply (UMULL), which
# the 31-bit big-integer and elliptic-curve code uses; Thumb calls it through thunks.
FLAGS = ['-marm', '-O2', '-DBR_USE_URANDOM=0', '-DBR_USE_WIN32_RAND=0', '-DBR_USE_UNIX_TIME=0',
         '-DBR_USE_WIN32_TIME=0', '-DBR_LOMUL=0', '-DBR_RDRAND=0', '-DBR_AES_X86NI=0', '-DBR_SSE2=0',
         '-DBR_POWER8=0', '-DBR_INT128=0', '-DBR_UMUL128=0']
CURVES = {'1.2.840.10045.3.1.7': 23, '1.3.132.0.34': 24, '1.3.132.0.35': 25}


# ---------- DER ----------

def der(data, at=0):
    """(tag, header length, content length) of the element at `at`."""
    tag, first = data[at], data[at+1]
    if first < 0x80:
        return tag, 2, first
    count = first & 0x7f
    return tag, 2+count, int.from_bytes(data[at+2:at+2+count], 'big')


def children(data, at=0):
    tag, header, length = der(data, at)
    position, end = at+header, at+header+length
    while position < end:
        _, h, n = der(data, position)
        yield position, data[position:position+h+n]
        position += h+n


def oid(value):
    body = value[der(value)[1]:]
    parts = [body[0]//40, body[0] % 40]
    number = 0
    for byte in body[1:]:
        number = number << 7 | byte & 0x7f
        if not byte & 0x80:
            parts.append(number)
            number = 0
    return '.'.join(map(str, parts))


def content(value):
    return value[der(value)[1]:]


def anchor(certificate):
    """(subject DN, key) where key is ('rsa', n, e) or ('ec', curve, point)."""
    tbs = list(children(certificate))[0][1]
    fields = [item for _, item in children(tbs)]
    if fields[0][0] == 0xa0:  # explicit version
        fields = fields[1:]
    subject, spki = fields[4], fields[5]
    algorithm, key = [item for _, item in children(spki)]
    parts = [item for _, item in children(algorithm)]
    bits = content(key)[1:]  # skip unused-bits byte
    kind = oid(parts[0])
    if kind == '1.2.840.113549.1.1.1':
        n, e = [content(item) for _, item in children(bits)]
        return subject, ('rsa', n.lstrip(b'\0'), e.lstrip(b'\0'))
    if kind == '1.2.840.10045.2.1':
        curve = CURVES.get(oid(parts[1]))
        return (subject, ('ec', curve, bits)) if curve else None
    return None


def c_bytes(name, data):
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i+16]) for i in range(0, len(data), 16)]
    return f'static const unsigned char {name}[] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


def generate():
    pem = CERTIFICATES.read_text(encoding='utf-8')
    blocks = re.findall(r'-----BEGIN CERTIFICATE-----(.+?)-----END CERTIFICATE-----', pem, re.S)
    if not blocks:
        raise ValueError(f'No certificates in {CERTIFICATES}')
    lines = ['/* Generated by tools/build_browser.py: trust anchors and fonts. */', '#include "bearssl.h"', '']
    entries = []
    for index, block in enumerate(blocks):
        result = anchor(base64.b64decode(''.join(block.split())))
        if not result:
            continue
        subject, key = result
        name = f'TA{len(entries)}'
        lines.append(c_bytes(f'{name}_DN', subject))
        if key[0] == 'rsa':
            lines += [c_bytes(f'{name}_N', key[1]), c_bytes(f'{name}_E', key[2])]
            pkey = (f'{{ BR_KEYTYPE_RSA, {{ .rsa = {{ (unsigned char *){name}_N, sizeof {name}_N, '
                    f'(unsigned char *){name}_E, sizeof {name}_E }} }} }}')
        else:
            lines.append(c_bytes(f'{name}_Q', key[2]))
            pkey = f'{{ BR_KEYTYPE_EC, {{ .ec = {{ {key[1]}, (unsigned char *){name}_Q, sizeof {name}_Q }} }} }}'
        entries.append(f'    {{ {{ (unsigned char *){name}_DN, sizeof {name}_DN }}, BR_X509_TA_CA, {pkey} }}')
    lines.append('const br_x509_trust_anchor browser_anchors[] = {\n' + ',\n'.join(entries) + '\n};')
    lines.append(f'const unsigned browser_anchor_count = {len(entries)};\n')
    build_library()
    for size in 'sml':
        data = (LIBRARY/f'go1/font-{size}.bin').read_bytes()
        lines.append(c_bytes(f'font_{size}_data', data).replace('static const', 'const', 1))
    OUTPUT.mkdir(parents=True, exist_ok=True)
    target = OUTPUT/'browser_data.c'
    target.write_text('\n'.join(lines), encoding='ascii')
    return target, len(entries)


def build():
    if not (BEARSSL/'inc/bearssl.h').exists():
        raise ValueError(f'BearSSL is missing: extract bearssl-0.6.tar.gz into {BEARSSL.parent}')
    if not CERTIFICATES.exists():
        raise ValueError(f'Root certificates are missing: download https://curl.se/ca/cacert.pem to {CERTIFICATES}')
    data, anchors = generate()
    libraries = sorted(str(p) for p in (BEARSSL/'src').rglob('*.c'))
    includes = [ROOT/'apps/browser/libc', BEARSSL/'inc', BEARSSL/'src']
    program = compile_native(SOURCE, sources=[data], includes=includes, libraries=libraries, library_flags=FLAGS)
    (OUTPUT/'BROWSER.GO1').write_bytes(program)
    return program, anchors


HOST = OUTPUT/'browser_host.exe'


def build_host():
    """browser.c on the PC with sockets for the GO1 API (apps/browser/host_test.c), for tests."""
    import os
    import subprocess
    from .setup_arm_toolchain import EXECUTABLE as ZIG
    data, _ = generate()
    libraries = sorted(str(p) for p in (BEARSSL/'src').rglob('*.c'))
    environment = os.environ.copy()
    environment['ZIG_GLOBAL_CACHE_DIR'] = str(ROOT/'analysis/toolchains/cache')
    environment['ZIG_LOCAL_CACHE_DIR'] = str(ROOT/'analysis/toolchains/local-cache')
    command = [str(ZIG), 'cc', '-target', 'x86-windows-gnu', '-O1', '-w', '-Ipatches', f'-I{BEARSSL/"inc"}',
               f'-I{BEARSSL/"src"}', f'-I{ROOT/"apps/browser"}', str(ROOT/'apps/browser/host_test.c'), str(data),
               *libraries, '-lws2_32', '-o', str(HOST)]
    result = subprocess.run(command, cwd=ROOT, env=environment, capture_output=True, text=True)
    if result.returncode:
        raise ValueError('host build failed:\n'+result.stderr[-3000:])
    return HOST


def default_card():
    from .build_java_phone import default_card as card
    return card()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--card', type=Path)
    args = parser.parse_args()
    try:
        program, anchors = build()
        from .install_sd_app import install
        card = args.card or default_card()
        install(OUTPUT/'BROWSER.GO1', card)  # replaces an older build
    except (OSError, ValueError) as exc:
        parser.error(f'{exc}. Close the emulator before changing its SD image.')
    print(f'BROWSER.GO1: {len(program)} bytes, {anchors} trust anchors -> {card}')


if __name__ == '__main__':
    main()
